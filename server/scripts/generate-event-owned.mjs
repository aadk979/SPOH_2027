#!/usr/bin/env node
/**
 * Writes the list of event-owned models (ADR-001 §2) from the schema: every
 * model whose doc comment carries `/// @eventOwned`. The event-scope guard in
 * `platform/db` reads it, so a new table cannot be left out of the guard;
 * `tests/unit/eventOwned.test.ts` fails when the file is stale.
 *
 *   node scripts/generate-event-owned.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

const SCHEMA = new URL('../prisma/schema.prisma', import.meta.url);
const OUTPUT = new URL('../src/platform/db/eventOwned.generated.ts', import.meta.url);

/** Model names marked `@eventOwned` in the doc comment directly above them. */
export function eventOwnedModels(schema) {
  const models = [];
  let marked = false;
  for (const line of schema.split('\n')) {
    const trimmed = line.trim();
    if (trimmed.startsWith('///')) {
      marked ||= /@eventOwned\b/.test(trimmed);
      continue;
    }
    const model = /^model\s+(\w+)\s*\{/.exec(trimmed);
    if (model && marked) models.push(model[1]);
    marked = false;
  }
  return models.sort();
}

export function render(models) {
  return `// Generated by scripts/generate-event-owned.mjs from prisma/schema.prisma. Do not edit.
// Every model marked \`/// @eventOwned\` (ADR-001 §2).

export const EVENT_OWNED_MODELS = [
${models.map((model) => `  '${model}',`).join('\n')}
] as const;

export type EventOwnedModel = (typeof EVENT_OWNED_MODELS)[number];
`;
}

export function generate() {
  return render(eventOwnedModels(readFileSync(SCHEMA, 'utf8')));
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  writeFileSync(OUTPUT, generate());
  console.log('wrote src/platform/db/eventOwned.generated.ts');
}
