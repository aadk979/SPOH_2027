#!/usr/bin/env node
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';
import { z } from 'zod';
import { SETTINGS } from '../server/src/platform/settings/registry.ts';

/** The registry is authored once on the server; these DTOs are generated for the client. */
const target = fileURLToPath(
  new URL('../packages/shared/src/generated/settings/index.ts', import.meta.url),
);
const entries = Object.entries(SETTINGS).sort(([a], [b]) => a.localeCompare(b));

function typeOf(definition, schema) {
  if (definition.typeName) return definition.typeName;
  if (schema.type === 'integer' || schema.type === 'number') return 'number';
  if (schema.type === 'string') return 'string';
  if (schema.type === 'boolean') return 'boolean';
  throw new Error(`${definition.key}: declare typeName for this schema`);
}

const schemas = entries.map(([key, definition]) => [key, z.toJSONSchema(definition.schema)]);
const types = schemas.map(
  ([key, schema]) => `  ${JSON.stringify(key)}: ${typeOf(SETTINGS[key], schema)};`,
);
const metadata = Object.fromEntries(
  entries.map(([key, definition]) => {
    const { schema, typeName: _typeName, normalise: _normalise, ...publicMetadata } = definition;
    return [key, { ...publicMetadata, jsonSchema: z.toJSONSchema(schema) }];
  }),
);
const defaults = Object.fromEntries(entries.map(([key, definition]) => [key, definition.default]));
const schemaLines = schemas.map(([key, jsonSchema]) => {
  const definition = SETTINGS[key];
  const source = `z.fromJSONSchema(${JSON.stringify(jsonSchema)})`;
  const normalised =
    definition.normalise === 'trim'
      ? `z.preprocess((value) => typeof value === 'string' ? value.trim() : value, ${source})`
      : source;
  return `  ${JSON.stringify(key)}: ${normalised} as z.ZodType<GeneratedSettingValues[${JSON.stringify(key)}]>,`;
});

const source = `/* Generated by scripts/generate-settings.mjs from server/src/platform/settings/registry.ts. Do not edit. */
import { z } from 'zod';
import type { CountsMode, VisitorDataMode } from '../../contracts/eventSettings/modes.js';

export interface GeneratedSettingValues {
${types.join('\n')}
}

export const GENERATED_SETTING_DEFAULTS = ${JSON.stringify(defaults)} as GeneratedSettingValues;
export const GENERATED_SETTING_METADATA = ${JSON.stringify(metadata)} as const;
export type GeneratedSettingKey = keyof GeneratedSettingValues;
export const GENERATED_SETTING_SCHEMAS: { [Key in GeneratedSettingKey]: z.ZodType<GeneratedSettingValues[Key]> } = {
${schemaLines.join('\n')}
};
`;
const prettierOptions = await prettier.resolveConfig(target);
const formatted = await prettier.format(source, {
  ...prettierOptions,
  parser: 'typescript',
  filepath: target,
});
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== formatted) {
    console.error('generated settings are stale; run npm run settings:generate');
    process.exitCode = 1;
  } else {
    console.log('generated settings match the registry');
  }
} else {
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, formatted);
  console.log(`generated ${entries.length} setting contracts`);
}
